import { defineArrayMember, defineField, defineType } from "sanity";
import { ReferenceNote } from "../components/ReferenceNote";

// A service, mirroring ServiceData in src/data/services.ts field for field, in the same order and
// with the same required fields. REFERENCE COPY ONLY: the site reads services from the code, never
// from this type. Fill or refresh it with `npm run import:services -- --commit`.
// Extras beyond ServiceData: the reference note (stores nothing), and order for sorting in Studio.
// Tabs follow /services/<slug> from top to bottom.
export default defineType({
  name: "service",
  title: "Service (reference copy)",
  type: "document",
  groups: [
    { name: "service", title: "Service", default: true },
    { name: "hero", title: "Hero" },
    { name: "deliverables", title: "Deliverables" },
    { name: "impact", title: "Why it matters" },
    { name: "process", title: "Process steps" },
    { name: "cta", title: "Closing call to action" },
    { name: "seo", title: "SEO" },
    { name: "unused", title: "Not shown yet" },
  ],
  fields: [
    defineField({
      name: "referenceNote",
      title: "Reference note",
      type: "string",
      readOnly: true,
      group: ["service", "hero", "deliverables", "impact", "process", "cta", "seo", "unused"],
      components: { field: ReferenceNote },
    }),
    defineField({
      name: "slug",
      title: "Web address",
      type: "slug",
      description: "The page address: /services/<slug>, for example brand-identity. Generate it from the service name.",
      options: { source: "name", maxLength: 96 },
      group: "service",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "number",
      title: "Service number",
      type: "string",
      description: "Two digits, for example 01. Not shown on the service page today; sets its place among the four services.",
      group: "service",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "name",
      title: "Service name",
      type: "string",
      description: "The full name, for example Brand Identity and Visual Design. Used on the Plan a … Project button at the bottom of the page, in the browser tab when the SEO title is empty, and in Brand Pulse results.",
      group: "service",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "subtitle",
      title: "Hero service name",
      type: "string",
      description: "The small line above the hero heading.",
      group: "hero",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "headline",
      title: "Hero heading",
      type: "string",
      description: "The large heading at the top of the page. It names the problem the service solves.",
      group: "hero",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "description",
      title: "Hero text",
      type: "text",
      rows: 3,
      description: "The paragraph under the hero heading.",
      group: "hero",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "tagline",
      title: "Tagline",
      type: "string",
      description: "One short line about the service. Kept in the code but not shown on the site today.",
      group: "unused",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "seoTitle",
      title: "SEO title",
      type: "string",
      description: "The browser tab and search result title. The studio name is added automatically.",
      group: "seo",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "seoDescription",
      title: "SEO description",
      type: "text",
      rows: 3,
      description: "The search result and link preview text.",
      group: "seo",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "gradient",
      title: "Background gradient",
      type: "string",
      description: "A CSS gradient, copied exactly. Kept in the code but not shown on the site today.",
      group: "unused",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "deliverables",
      title: "Deliverables",
      type: "array",
      description: "(01) What you get: the numbered list of deliverables. The count above the list updates itself.",
      group: "deliverables",
      validation: (rule) => rule.required(),
      of: [
        defineArrayMember({
          name: "serviceDeliverable",
          title: "Deliverable",
          type: "object",
          fields: [
            defineField({
              name: "name",
              title: "Name",
              type: "string",
              description: "The deliverable, for example Logo System.",
              validation: (rule) => rule.required(),
            }),
            defineField({
              name: "description",
              title: "Description",
              type: "text",
              rows: 2,
              description: "One sentence under the deliverable name.",
              validation: (rule) => rule.required(),
            }),
          ],
          preview: { select: { title: "name", subtitle: "description" } },
        }),
      ],
    }),
    defineField({
      name: "impact",
      title: "Why it matters",
      type: "object",
      description: "(02) Why it matters: the heading and paragraph after the deliverables.",
      group: "impact",
      validation: (rule) => rule.required(),
      fields: [
        defineField({
          name: "heading",
          title: "Heading",
          type: "string",
          description: "The large line in this section.",
          validation: (rule) => rule.required(),
        }),
        defineField({
          name: "body",
          title: "Text",
          type: "text",
          rows: 4,
          description: "The paragraph under the heading.",
          validation: (rule) => rule.required(),
        }),
      ],
    }),
    defineField({
      name: "process",
      title: "Process steps",
      type: "array",
      description: "(04) How we do it: the steps in the accordion, in order.",
      group: "process",
      validation: (rule) => rule.required(),
      of: [
        defineArrayMember({
          name: "serviceProcessStep",
          title: "Process step",
          type: "object",
          fields: [
            defineField({
              name: "step",
              title: "Step number",
              type: "string",
              description: "Two digits, for example 01, shown beside the step name.",
              validation: (rule) => rule.required(),
            }),
            defineField({
              name: "name",
              title: "Step name",
              type: "string",
              description: "For example Discovery.",
              validation: (rule) => rule.required(),
            }),
            defineField({
              name: "description",
              title: "Description",
              type: "text",
              rows: 2,
              description: "The sentence that opens under the step name.",
              validation: (rule) => rule.required(),
            }),
          ],
          preview: {
            select: { step: "step", name: "name", subtitle: "description" },
            prepare: ({ step, name, subtitle }) => ({ title: [step, name].filter(Boolean).join("  "), subtitle }),
          },
        }),
      ],
    }),
    defineField({
      name: "ctaHeading",
      title: "Closing heading",
      type: "string",
      description: "The heading in the dark Next step section at the bottom of the page.",
      group: "cta",
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: "order",
      title: "Order in Studio",
      type: "number",
      description: "Sorts this list in Studio only. Lower numbers come first.",
      group: "service",
    }),
  ],
  orderings: [
    {
      title: "Display Order",
      name: "orderAsc",
      by: [{ field: "order", direction: "asc" }],
    },
  ],
  preview: {
    // title: the older service documents used a title field instead of a name.
    select: { number: "number", name: "name", title: "title" },
    prepare: ({ number, name, title }) => ({
      title: name ? [number, name].filter(Boolean).join("  ") : title || "Untitled service",
      subtitle: name ? "Reference copy" : "Older document, not part of the mirror",
    }),
  },
});
